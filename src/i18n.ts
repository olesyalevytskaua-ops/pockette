/** Ukrainian plural: 1 картка, 2–4 картки, 5+ карток (11–14 take the "many" form). */
function ukPlural(n: number, one: string, few: string, many: string) {
  const d = n % 10, h = n % 100;
  return d === 1 && h !== 11 ? one : d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
}

